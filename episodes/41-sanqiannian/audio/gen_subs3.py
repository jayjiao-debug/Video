"""Generate src/qq/subs3.ts from vo_timeline_v3.json (measured clips). Lines over 16 字 are split at the comma nearest the middle."""
import json, subprocess, re
L = json.load(open('vo_timeline_v3.json'))
def dur(f, extra):
    d = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f + '.mp3'], capture_output=True, text=True).stdout)
    m = re.search(r'atempo=([0-9.]+)', extra or ''); return d / float(m.group(1)) if m else d
def nchar(s): return len(re.sub(r'[「」：，。？！、——…（）·\s]', '', s))
subs = []
for f, at, fx, ex, ss in L:
    d = dur(f, ex)
    for a, b, zh, nat in ss:
        s0, s1 = at + a, at + (b if b is not None else d + 0.35)
        cuts = [i for i, ch in enumerate(zh) if ch in '，。？：' and 0 < i < len(zh) - 3]
        if nchar(zh) > 16 and cuts:
            i = min(cuts, key=lambda i: abs(i - len(zh) / 2)); p1, p2 = zh[:i + 1], zh[i + 1:]
            q = s0 + (s1 - s0) * len(p1) / len(zh)
            if p1.count('「') > p1.count('」'): p1, p2 = p1 + '」', '「' + p2
            subs += [[s0, q, p1, nat], [q, s1, p2, nat]]
        else: subs.append([s0, s1, zh, nat])
subs.sort(key=lambda s: s[0])
for i in range(len(subs)):   # hold each line ≥ 2.2 s where the next line allows; never overlap the next
    nxt = subs[i + 1][0] - 0.08 if i + 1 < len(subs) else 1e9
    subs[i][1] = min(max(subs[i][1], subs[i][0] + 2.2), nxt)
subs[0][0] = -0.3   # full opacity on frame 0
for sb in subs:
    if sb[2].startswith('然后，系统崩溃了'): sb[1] = max(sb[1], 145.9)
T = lambda x: json.dumps(x, ensure_ascii=False)
lines = ',\n\t'.join('[' + ', '.join([f'{s[0]:.2f}', f'{s[1]:.2f}', T(s[2])] + ([T(s[3])] if s[3] else [])) + ']' for s in subs)
lab = [(18.965, 34.836, '约公元前 1200 年', '商 · 殷墟'), (34.836, 54.875, '757 年', '杜甫 · 长安'), (54.875, 72.80, '1825 / 1844 年', '莫尔斯 · 华盛顿'), (72.80, 90.63, '1860 年', '斯科特 · 巴黎'),
       (90.63, 110.17, '1876 年 3 月 10 日', '贝尔 · 波士顿'), (110.17, 128.282, '1901 年 12 月 12 日', '马可尼 · 康沃尔 → 纽芬兰'), (128.282, 143.85, '1969 年 10 月 29 日', '阿帕网 · UCLA → SRI'),
       (145.43, 160.67, '1987 年 9 月', '一封电子邮件 · 北京 → 德国'), (160.67, 172.6, '1977 年', '旅行者号 · 金唱片')]
LSTART = {18.965: 21.6, 34.836: 37.6}
labs = ',\n\t'.join(f'[{LSTART.get(a, a + 0.6):.3f}, {b - 0.95:.3f}, {T(y)}, {T(n)}]' for a, b, y, n in lab)
open('/home/claude/video/episodes/37-qiqing/remotion/src/qq/subs3.ts', 'w').write(f"""/* subtitles and era labels for the v3 cut — film times, generated by audio/gen_subs3.py from vo_timeline_v3.json. */
export type Line3 = [number, number, string, string?];
export const SUBS3: Line3[] = [
\t{lines},
];
export const LABELS3: [number, number, string, string][] = [
\t{labs},
];
""")
for s in subs: print(f'{s[0]:7.2f} {s[1]:7.2f} {nchar(s[2]):2d} {s[2]}')
