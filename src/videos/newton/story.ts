// HOW TO BUILD A SEGMENT (Qin's / Wanbi's rules; read all of it before you write code)
// =====================================================================================================================
// 1. The contract. shots/segX.ts exports SEG: Segment (type below):
//      export const SEG: Segment = { id: "A", from: SEGMENTS[0].from, to: SEGMENTS[0].to, enter(w) {...}, exit(w) {...}, pose(w, f) {...} };
//    from / to are inclusive absolute film frames and must equal SEGMENTS[...] (segments = the scenes A-G of the lines
//    file). The engine, for every rendered frame f:
//      if the segment changed (or this is the first frame of the page):  old.exit(w); SEG.enter(w)
//      w.beginFrame(f);  const P = SEG.pose(w, f);  w.endFrame(P)
//    then draws the HUD layer (the vlog UI: REC, the scene's timestamp, the battery (hud/vlog.tsx); registered HUDs; the
//    title block and the fact card), P.overlays over it, the subtitle of frame f over that, and P.top over everything.
//
// 2. Any frame can be the first one (the farm renders chunks on fresh pages; a still is a fresh page). pose(w, f) is
//    a PURE function of f: it sets EVERY property it relies on, EVERY frame. Take time from f, never from w.t.
//    w.beginFrame(f) hides every figure and every prop, clears the place and resets every set param to its default.
//    Determinism: no Math.random, Date, performance.now in anything that reaches pixels. Use rng(seed) / hash(i, k).
//
// 3. THE WORLD CONTRACT, inside a shot, in this order:
//      w.setPlace("stairs" | "room" | "garden" | "street" | "schools" | "elaboratory")   FIRST: one island, its look and light
//      w.set.param("hour", "noon")                    per-frame dressing of the place that shows (sets/index.ts PARAMS);
//                                                     beginFrame resets every param; the figures' light follows the
//                                                     params when w.update() runs (so set params BEFORE update)
//      w.setCamera(cam)                               a CamPose (her eyes: 1.6 m, layout.ts EYE; cam.ts); return it in the Pose
//      const r = w.actor(NEWTON); r.set({ at, facing, pose, expr, gaze, turn, hands, seat, visible: true, ...speak(quote("nt", "A02"), f, id) })
//         a person not set is hidden
//      w.update()                                     solves the figures; r.handWorld(i) is valid only after it
//      w.prop("plate").put(at, { ... })               props: every frame (hidden again at the next one)
//      w.project(v) -> { x, y, z, front, on }         HUD that follows the world
//      return { camera, clock?, hud?, cards?, captions?, overlays?, top?, post?, title? }   Film calls w.endFrame(P)
//
// 4. Frames: every frame number comes from beats.ts (BEAT.X.name, placeAt, TITLE_SPAN) or from line() / lineId() /
//    cap() / capWord() / quote() / SEGMENTS / CARDS here; every mark from layout.ts / layout/<place>.ts; every
//    on-screen string is L(zh, en). A beat that is not in beats.ts is derived in the segment's own file the same way
//    (capWord("A01", "好").from for a ji line, capWord("F14", "burn").from for an nt / hm line: the word in the language
//    the line is SPOKEN in).
//    Screen zones (px on 1080 x 1920, layout.ts SCREEN): nothing that matters above y 150 or in the subtitle band
//    (SCREEN.capTop..capBottom: Chinese large, English small under it) or below SCREEN.bottom; faces in the upper third
//    but out of the vlog UI's corners (SCREEN.rec top left, SCREEN.battery top right; for the first 2 s of every scene the
//    timestamp holds BIG in the top-left corner: hud VLOG_RECT.stampBig, about x 50..400, y 240..345);
//    the fact card's slot is MID-LEFT (hud/ hudRectsAt(f) gives its box while it shows); the title block sits on the
//    shut door (TITLE_SPAN). Her mic and her hands are NEVER DRAWN (props/index.ts INVISIBLE; Jay, 14 Nov): what she
//    holds or does moves as if by an invisible hand. Mouths move ONLY inside a character's own line:
//    ...speak(quote("nt", "A02"), f, id). ji (the reporter) is the camera: never a figure.
// =====================================================================================================================
