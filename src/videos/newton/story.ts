// ---------------------------------------------------------------------------------------------------- the cards
/** a fact card (5 in the film): shown only while nobody speaks, from the end of its line (+ its card_delay) for its
 *  card_hold seconds: n / id = the line it follows, from / to inclusive frames, zh (large) and en (small under it);
 *  text = L(zh, en) */
export type Card = { n: number; id: string; from: number; to: number; zh: string; en: string; text: string };
export const CARDS: Card[] = CARD_RAW.map(([n, id, from, to, zh, en]) => ({ n, id, from, to, zh, en, text: L(zh, en) }));
/** the fact card shown on frame f, or null */
export const cardAt = (f: number): Card | null => CARDS.find((c) => f >= c.from && f <= c.to) ?? null;
/** the fact card after line `id` ("A03"). Throws when that line has none. */
export const card = (id: string): Card => { const c = CARDS.find((x) => x.id === id || x.n === lineNum(id)); if (!c) throw new Error(`card("${id}"): that line has no fact card`); return c; };
