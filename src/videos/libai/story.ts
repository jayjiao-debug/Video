// src/videos/qin/story.ts. The design: PLAN.md in this folder (the bible, the storyboard of section 8, the lanes).
// Data files (WP1; segment builders treat them as read-only and ask for changes in /home/user/libai_work/requests.md):
//   story.ts     this file: FPS / frames, the dialogue lines (+ their English, lineEn), quotes, the Segment / Pose / Place
//                types, SEGMENTS, CARDS, SCENE_LABEL, the HUD hook; easing + RNG helpers (re-exported from group/story.ts);
//                cap / capWord / capsOf
//   beats.ts     the film's named beats per scene (BEAT.A.micIn ...), the place of every frame (placeAt), the title span,
//                all looked up from the timing data
//   voice.ts, captions.ts   GENERATED by scripts/libai/gen_timing.py: never edit, never copy a number out of them
//   captions_en.ts          the English-version captions (a stub = the Chinese timing until an English pass generates it)
//   lang.ts      LANG / EN / L (src/kit/film/lang.ts) and TXT
// The world: world.ts (World), sets/, props/, people.ts, layout.ts + layout/ (islands, marks, named cameras), Film.tsx
// (the composition "LibaiFilm"), shots/common.ts (the verbs), shots/segA.ts .. segI.ts, hud/. README.md has the contract.
// =====================================================================================================================
// HOW TO BUILD A SEGMENT (Qin's / Wanbi's / Hongmen's rules, unchanged; read all of it before you write code)
// =====================================================================================================================
// 1. The contract. shots/segX.ts exports SEG: Segment (type below):
//      export const SEG: Segment = { id: "A", from: SEGMENTS[0].from, to: SEGMENTS[0].to, enter(w) {...}, exit(w) {...}, pose(w, f) {...} };
//    from / to are inclusive absolute film frames and must equal SEGMENTS[...] (segments = the scenes A-I of the lines
//    file). The engine, for every rendered frame f:
//      if the segment changed (or this is the first frame of the page):  old.exit(w); SEG.enter(w)
//      w.beginFrame(f);  const P = SEG.pose(w, f);  w.endFrame(P)
//    then draws the HUD layer (the title block, the fact cards, the stamps, the end names, registered HUDs), P.overlays
//    over it, the caption of frame f (Chinese + the line's English) over that, and P.top over everything.
//
// 2. Any frame can be the first one (the farm renders chunks on fresh pages; a still is a fresh page). pose(w, f) is
//    a PURE function of f: it sets EVERY property it relies on, EVERY frame. Take time from f, never from w.t.
//    w.beginFrame(f) hides every figure and every prop, clears the place and resets every set param to its default.
//    Determinism: no Math.random, Date, performance.now in anything that reaches pixels. Use rng(seed) / hash(i, k).
//
// 3. THE WORLD CONTRACT, inside a shot, in this order:
//      w.setPlace("market" | "yard" | "room" | "huangzhou" | "pines" | "river" | "beach" | "temple")   FIRST: one island
//      w.set.param("lantern", 1)                      per-frame dressing of the place that shows (sets/index.ts PARAMS);
//                                                     beginFrame resets every param (setView is the engine's, never a segment's)
//      w.setCamera(cam)                               a CamPose (her eyes: 1.50 m, layout.ts EYE); return it in the Pose
//      const r = w.actor(SU); r.set({ at, facing, pose, expr, gaze, turn, hands, seat, visible: true, ...speak(quote("su", "A02"), f, id) })
//         a person not set is hidden
//      w.update()                                     solves the figures; r.handWorld(i) is valid only after it
//      w.prop("spine").put(hand, { grip: "pair" })    props: pin the hand to a computed point, put the prop there
//      w.project(v) -> { x, y, z, front, on }         HUD that follows the world
//      return { camera, clock?, hud?, cards?, captions?, overlays?, top?, post? }     Film calls w.endFrame(P)
//    An actor swap (SU -> SU_DAN) = two actors, one visible (swapTo in shots/common.ts).
//
// 4. Frames: every frame number comes from beats.ts (BEAT.X.name, placeAt) or from line() / lineId() / cap() /
//    capWord() / quote() / SEGMENTS / CARDS here; every mark from layout.ts; every on-screen string is L(zh, en).
//    A beat that is not in beats.ts is derived in the segment's own file the same way (capWord("B06", "撒盐").from is
//    the frame the word's first syllable starts on, also inside a caption group).
//    Screen zones (px on 1080 x 1920, layout.ts SCREEN): nothing that matters above y 210, in the caption band
//    1190-1520 (Chinese + English), below 1613, or at x > 930 for y > 900; the title block owns the top centre
//    (y 230-420) for the first 3 s, a fact card the middle left (x 56-760, y 780-1080) while it shows, a stamp the
//    top left (x 60-260, y 230-430) at the start of H and I, the end names the middle third in I (hud/ hudRectsAt(f)).
//    Faces in the upper third (eyes y < 700). Mouths move ONLY inside a character's own line:
//    ...speak(quote("su", "A02"), f, id). ji (the reporter) is the camera: never a figure (her hand and red mic: her.ts).
// =====================================================================================================================
