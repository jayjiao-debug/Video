// ---------------------------------------------------------------------------------------------------- the contract
export type Vec3 = [number, number, number];
export type V3Like = Vec3 | THREE.Vector3;
/** a camera pose: camera.up = up ?? (0,1,0); position = pos; lookAt(look); rotateZ(roll ?? 0); fov (vertical, degrees) */
export type CamPose = { pos: V3Like; look: V3Like; fov: number; roll?: number; up?: Vec3; near?: number; far?: number };
export type PostPose = {
  /** depth of field: focus distance (m) and blur-disc radius in px (at 1080 x 1920) of things at infinity; 0 = off */
  dof?: { focus: number; amount: number } | null;
  /** bloom intensity (threshold 1.0: only emissive / glowing things bloom); default: the place's */
  bloom?: number;
  /** default: the place's grade (sets/index.ts PlaceLook.grade), else GRADE_FILM */
  grade?: GradeParams; gradeAmount?: number;
  /** ink outline strength 0..1 (1 = default) */
  ink?: number;
  /** N8AO intensity multiplier (1 = the place's value) */
  ao?: number;
  /** scene.background instead of the place's (a CSS colour) */
  bg?: string;
};
export type Pose = {
  camera: CamPose;
  /** [x, z]: where the key light's shadow frustum is centred (default: under the camera's look point) */
  focus?: [number, number];
  /** seconds for the place's own animation (lanterns, wind, rain): default f / FPS */
  clock?: number;
  /** 2D layer above the 3D picture and the HUD, below the captions (hud/ functions; frag(...) joins several) */
  overlays?: React.ReactNode;
  /** 2D layer above the captions */
  top?: React.ReactNode;
  post?: PostPose;
  /** false hides the caption on this frame */
  captions?: boolean;
  /** false hides the whole HUD layer on this frame (title, cards, stamps, end names, the registered HUDs) */
  hud?: boolean;
  /** false hides the fact card and the title block on this frame (the stamps and the end names stay) */
  cards?: boolean;
  /** a debug label for the animatic (drawn only with the input prop slate: true): e.g. "A3 turn" */
  slate?: string;
};
export type Segment = {
  id: string;
  /** inclusive absolute frames */
  from: number; to: number;
  enter(w: World): void;
  exit(w: World): void;
  /** pure function of f: pose the world and the camera, return what to show */
  pose(w: World, f: number): Pose;
};

// ---------------------------------------------------------------------------------------------------- the HUD hook
/** EXTRA HUDs: things that stay on screen across shots and segments besides the title, cards, stamps and end names (which Film.tsx
 *  draws itself from hud/). Film.tsx draws every registered HUD on every frame, above the 3D picture and UNDER the
 *  shot's own overlays, unless the shot's Pose says hud: false:  registerHud("name", (f, P) => node)
 *  A HUD is a pure function of the frame (and of the frame's Pose). Registering the same name again replaces it. */
export type Hud = (f: number, P: Pose) => React.ReactNode;
const HUDS: { name: string; draw: Hud }[] = [];
export const registerHud = (name: string, draw: Hud) => {
  const i = HUDS.findIndex((x) => x.name === name);
  if (i >= 0) HUDS[i] = { name, draw }; else HUDS.push({ name, draw });
};
/** the registered HUDs in the order they were registered (Film.tsx) */
export const huds = (): readonly { name: string; draw: Hud }[] => HUDS;

// ---------------------------------------------------------------------------------------------------- the lines
/** a line of the dialogue in frames: from = first frame of speech, to = last; pre / after = the lines file's silent
 *  beat before it / hold after it, in FRAMES; preFrom = from - pre (where its silent beat starts: the action before it) */
export type VoiceLine = {
  n: number; id: string; scene: SceneId; who: Speaker; text: string;
  from: number; to: number; start: number; end: number;
  pre: number; after: number; preFrom: number;
};
const META = new Map(LINE_RAW.map(([n, id, scene, who, pre, after]) => [n, { id, scene: scene as SceneId, who, pre, after }]));
/** the dialogue lines; n starts at 1 (LINES[n - 1]) */
export const LINES: VoiceLine[] = VOICE_RAW.map(([n, s, e, text]) => {
  const m = META.get(n);
  if (!m) throw new Error(`story: line ${n} has no LINE_RAW entry`);
  const from = Math.round(s * FPS), pre = Math.round(m.pre * FPS);
  return { n, id: m.id, scene: m.scene, who: m.who, text, start: s, end: e, from, to: Math.round(e * FPS), pre, after: Math.round(m.after * FPS), preFrom: from - pre };
});
export const SPEECH_END = Math.round(VOICE_END_S * FPS);
/** the line with number n (1-based) or id ("A03"). Throws when there is no such line. */
export const line = (n: number | string): VoiceLine => {
  const k = lineNum(n), l = LINES[k - 1];
  if (!l || l.n !== k) throw new Error(`line(${JSON.stringify(n)}): the dialogue has ${LINES.length} lines`);
  return l;
};
/** the line with this id: lineId("A03") -> { from, to, who, ... } (the same as line("A03")) */
export const lineId = (id: string): VoiceLine => line(id);
/** the line spoken at frame f (or null in a pause) */
export const lineAt = (f: number) => LINES.find((l) => f >= l.from && f <= l.to) ?? null;
/** the number of the line that frame f belongs to as PICTURE: the last line whose silent beat has started */
export const lineNo = (f: number) => { let n = 1; for (const l of LINES) if (f >= l.preFrom - 2) n = l.n; return n; };
const EN_OF = new Map(LINE_EN.map(([n, en]) => [n, en]));
/** THE LINE'S ENGLISH (voice.ts LINE_EN): lineEn("A05") / lineEn(5) = "Look! There's still meat between the bones!"
 *  (the caption shows it small under the Chinese for the whole line). Throws when the line has none. */
export const lineEn = (n: number | string): string => {
  const k = lineNum(n), en = EN_OF.get(k);
  if (en === undefined) throw new Error(`lineEn(${JSON.stringify(n)}): voice.ts LINE_EN has no English for line ${k}`);
  return en;
};

// ---------------------------------------------------------------------------------------------------- quotes
/** a line as its speaker's own words (every line is one): who speaks, the absolute frames, the seconds, the syllable
 *  count (for rigSpeak) and the text */
export type Quote = { line: number; who: Speaker; text: string; syl: number; from: number; to: number; start: number; end: number };
/** one per line (English: the same lines' quotes with the times and syllables of the English dialogue, once
 *  captions_en.ts has them) */
export const QUOTES: Quote[] = EN && QUOTE_RAW_EN.length
  ? QUOTE_RAW_EN.map(([ln, who, s, e, syl, text]) => ({ line: ln, who, text, syl, start: s, end: e, from: Math.round(s * FPS), to: Math.round(e * FPS) }))
  : QUOTE_RAW.map(([ln, who, s, e, text]) => ({ line: ln, who, text, syl: [...text.replace(/[^一-鿿]/g, "")].length, start: s, end: e, from: Math.round(s * FPS), to: Math.round(e * FPS) }));
/** the line `n` (number or id) as a quote of `who`: quote("di", "A03"). Throws when that line is not `who`'s. */
export const quote = (who: Speaker, n: number | string): Quote => {
  const k = lineNum(n), q = QUOTES.find((x) => x.line === k);
  if (!q) throw new Error(`quote("${who}", ${JSON.stringify(n)}): no such line`);
  if (q.who !== who) throw new Error(`quote("${who}", ${JSON.stringify(n)}): that line is ${q.who}'s`);
  return q;
};
/** every line of `who`, in order */
export const quotesOf = (who: Speaker): Quote[] => QUOTES.filter((q) => q.who === who);

