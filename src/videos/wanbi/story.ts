// 《完璧归赵》 (WanbiFilm) film engine: timing, the segment contract and the segment table. A cut-down copy of
// src/videos/hongmen/story.ts. The design: BIBLE.md (the world), STORYBOARD.md (the 33 shots), BUILD_PLAN.md (files and
// packages), all in this folder.
// Data files (WP1a; FROZEN after it: segment builders treat them as read-only and ask for changes):
//   story.ts     this file: FPS / frames, voice lines, quotes, the Segment / Pose / Place types, SEGMENTS, the HUD
//                hook; easing + RNG helpers (re-exported from group/story.ts); cap / capWord / capsOf (captions.ts)
//   beats.ts     the film's named beats (the 33 shots with their placed lists, hits, tags, the jade holder, the HUD's
//                beats), all looked up from the caption data
//   voice.ts, captions.ts   GENERATED by scripts/wanbi/gen_timing.py: never edit, never copy a number out of them
//   captions_en.ts          the English captions (a stub = the Chinese timing until WP13 generates it)
//   lang.ts      LANG / EN / L (src/kit/film/lang.ts) and TXT.source
// The world (WP1b on): world.ts (World), sets/, props/, people.ts, layout.ts + layout/ (marks and the 23 CAMS),
// Film.tsx (the composition "WanbiFilm"), shots/common.ts (the verbs), shots/segA.ts .. segE.ts, hud/ (WP6).
// =====================================================================================================================
// HOW TO BUILD A SEGMENT (Hongmen's rules, unchanged; read all of it before you write code)
// =====================================================================================================================
// 1. The contract. shots/segX.ts exports SEG: Segment (type below):
//      export const SEG: Segment = { id: "A", from: SEGMENTS[0].from, to: SEGMENTS[0].to, enter(w) {...}, exit(w) {...}, pose(w, f) {...} };
//    from / to are inclusive absolute film frames and must equal SEGMENTS[...] (A = lines 1-6, B = 7-11, C = 12-15,
//    D = 16-19, E = 20-23). The engine, for every rendered frame f:
//      if the segment changed (or this is the first frame of the page):  old.exit(w); SEG.enter(w)
//      w.beginFrame(f);  const P = SEG.pose(w, f);  w.endFrame(P)
//    then draws the HUD layer, P.overlays over it, the caption of frame f over that, and P.top over everything.
//
// 2. Any frame can be the first one (the farm renders chunks on fresh pages; a still is a fresh page). pose(w, f) is
//    a PURE function of f: it sets EVERY property it relies on, EVERY frame. Take time from f, never from w.t.
//    w.beginFrame(f) hides every figure and every prop, clears the place, turns the ceremony and the map stand off.
//    Determinism: no Math.random, Date, performance.now in anything that reaches pixels. Use rng(seed) / hash(i, k).
//
// 3. THE WORLD CONTRACT (BUILD_PLAN.md section 2), inside a shot, in this order:
//      w.setPlace("hall" | "zhao" | "road")          FIRST: shows one island, sets its look and light
//      w.set.setCeremony(0..1); w.set.setMapStand(on)  (setView is called by endFrame, never by a segment)
//      w.setCamera(CAMS.hook)                         or a mixed CamPose (camMix) for moves and whips; return it in the Pose
//      const r = w.actor(LIN); r.set({ at, facing, pose, expr, gaze, turn, hands, seat, visible: true, ...speak(q, f, id) })
//         each shot sets exactly its placed list (beats.ts SHOTS[].placed); a person not set is hidden
//      w.update()                                     solves the figures; r.handWorld(i) is valid only after it
//      w.prop("jade").put(hand, { scale: 1.5, grip: "rim" })   pin the hand to a computed point, put the prop there
//      w.project(v) -> { x, y, z, front, on }         HUD that follows the world (map cities, ring, stage circle)
//      return { camera, clock?, hud?, overlays? }     Film calls w.endFrame(P)
//    An actor swap (LIN -> LIN_RAGE) = two actors, one visible (swapTo in shots/common.ts).
//
// 4. Frames: every frame number comes from beats.ts (SHOTS, HIT, TAG, BEAT, HOLDER) or from line() / cap() /
//    capWord() / quote() / SEGMENTS here; every mark and camera from layout.ts; every on-screen string is L(zh, en).
//    A beat that is not in beats.ts is derived in the segment's own file the same way (capWord(line, word).from is the
//    frame the word's first syllable starts on, also inside a caption group).
//    Screen zones (px on 1080 x 1920, layout.ts SCREEN): nothing that matters above y 210, in the caption band
//    1190-1498, below 1613, or at x > 930 for y > 900; the source tag owns the top-left corner, the jade chip the top
//    right (x 780-984, y 215-310). Mouths move ONLY inside a character's own quote: ...speak(quote("lin", 6), f, id).
// =====================================================================================================================
