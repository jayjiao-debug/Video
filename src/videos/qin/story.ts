/** the seven build segments = the scenes, from the generated SEGMENT_RAW: a scene starts where its first line's silent
 *  beat starts (C: 2 frames before its first word: C01's beat is B's cutaway) */
export const SEGMENTS: { id: SceneId; from: number; to: number; lines: [number, number]; what: string }[] =
  SEGMENT_RAW.map(([id, l0, l1, from, to]) => ({ id: id as SceneId, from, to, lines: [l0, l1], what: WHAT[id] ?? "" }));
if (SEGMENTS[0].from !== 0 || SEGMENTS[SEGMENTS.length - 1].to !== TOTAL - 1) throw new Error("story: SEGMENT_RAW does not cover the film");
SEGMENTS.forEach((s, i) => { if (i && s.from !== SEGMENTS[i - 1].to + 1) throw new Error(`story: segment ${s.id} does not follow ${SEGMENTS[i - 1].id}`); });
/** the segment that frame f belongs to */
export const segmentAt = (f: number) => SEGMENTS.find((s) => f >= s.from && f <= s.to) ?? (f < 0 ? SEGMENTS[0] : SEGMENTS[SEGMENTS.length - 1]);
/** the segment with this id */
export const seg = (id: SceneId) => { const s = SEGMENTS.find((x) => x.id === id); if (!s) throw new Error(`seg("${id}"): no such segment`); return s; };

// ---------------------------------------------------------------------------------------------------- the cards
/** a fact card: shown from the end of its line for the line's "after" seconds (else 2.4 s): n / id = the line it
 *  follows, from / to inclusive frames, text = L(zh, en) */
export type Card = { n: number; id: string; from: number; to: number; zh: string; en: string; text: string };
export const CARDS: Card[] = CARD_RAW.map(([n, id, from, to, zh, en]) => ({ n, id, from, to, zh, en, text: L(zh, en) }));
/** the fact card shown on frame f, or null */
export const cardAt = (f: number): Card | null => CARDS.find((c) => f >= c.from && f <= c.to) ?? null;
/** the fact card after line `id` ("A01"). Throws when that line has none. */
export const card = (id: string): Card => { const c = CARDS.find((x) => x.id === id || x.n === lineNum(id)); if (!c) throw new Error(`card("${id}"): that line has no fact card`); return c; };

