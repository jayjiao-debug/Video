//   story.ts     this file: FPS / frames, the dialogue lines, quotes, the Segment / Pose / Place types, SEGMENTS, CARDS,
//                SCENE_TIME, the HUD hook; easing + RNG helpers (re-exported from group/story.ts); cap / capWord / capsOf
//   beats.ts     the film's named beats per scene (BEAT.A.turn ...), the place of every frame (placeAt), the title card,
//                all looked up from the timing data
//   voice.ts, captions.ts   GENERATED by scripts/qin/gen_timing.py: never edit, never copy a number out of them
//   captions_en.ts          the English captions (a stub = the Chinese timing until the English pass generates it)
//   lang.ts      LANG / EN / L (src/kit/film/lang.ts) and TXT
// The world: world.ts (World), sets/, props/, people.ts, layout.ts + layout/ (islands and marks), Film.tsx (the
// composition "QinFilm"), shots/common.ts (the verbs), shots/segA.ts .. segG.ts, hud/. README.md has the short contract.
// =====================================================================================================================
// HOW TO BUILD A SEGMENT (Wanbi's / Hongmen's rules, unchanged; read all of it before you write code)
// =====================================================================================================================
// 1. The contract. shots/segX.ts exports SEG: Segment (type below):
//      export const SEG: Segment = { id: "A", from: SEGMENTS[0].from, to: SEGMENTS[0].to, enter(w) {...}, exit(w) {...}, pose(w, f) {...} };
//    from / to are inclusive absolute film frames and must equal SEGMENTS[...] (segments = the scenes A-G of the lines
//    file). The engine, for every rendered frame f:
//      if the segment changed (or this is the first frame of the page):  old.exit(w); SEG.enter(w)
//      w.beginFrame(f);  const P = SEG.pose(w, f);  w.endFrame(P)
//    then draws the HUD layer (the vlog UI, the fact cards, the title card), P.overlays over it, the caption of frame f
//    over that, and P.top over everything.
//
// 2. Any frame can be the first one (the farm renders chunks on fresh pages; a still is a fresh page). pose(w, f) is
//    a PURE function of f: it sets EVERY property it relies on, EVERY frame. Take time from f, never from w.t.
//    w.beginFrame(f) hides every figure and every prop, clears the place and resets every set param to its default.
//    Determinism: no Math.random, Date, performance.now in anything that reaches pixels. Use rng(seed) / hash(i, k).
//
// 3. THE WORLD CONTRACT, inside a shot, in this order:
//      w.setPlace("corridor" | "hall" | "terrace" | "table" | "night" | "road" | "museum")   FIRST: one island, its look and light
//      w.set.param("carriages", 0.2)                  per-frame dressing of the place that shows (sets/index.ts PARAMS);
//                                                     beginFrame resets every param (setView is the engine's, never a segment's)
//      w.setCamera(cam)                               a CamPose (her eyes: 1.55 m, layout.ts EYE); return it in the Pose
//      const r = w.actor(EMPEROR); r.set({ at, facing, pose, expr, gaze, turn, hands, seat, visible: true, ...speak(quote("di", "A03"), f, id) })
//         a person not set is hidden
//      w.update()                                     solves the figures; r.handWorld(i) is valid only after it
//      w.prop("sword").put(hand, { grip: "hilt", rot })   props: pin the hand to a computed point, put the prop there
//      w.project(v) -> { x, y, z, front, on }         HUD that follows the world
//      return { camera, clock?, hud?, rec?, cards?, overlays? }     Film calls w.endFrame(P)
//    An actor swap (EMPEROR -> EMPEROR_BLUSH1) = two actors, one visible (swapTo in shots/common.ts), on a blink.
//
// 4. Frames: every frame number comes from beats.ts (BEAT.X.name, placeAt) or from line() / lineId() / cap() /
//    capWord() / quote() / SEGMENTS / CARDS here; every mark from layout.ts; every on-screen string is L(zh, en).
//    A beat that is not in beats.ts is derived in the segment's own file the same way (capWord("A12", "拍").from is the
//    frame the word's first syllable starts on, also inside a caption group).
//    Screen zones (px on 1080 x 1920, layout.ts SCREEN): nothing that matters above y 210, in the caption band
//    1190-1498, below 1613, or at x > 930 for y > 900; the REC dot and the 时辰 timestamp own the top row (y 205-255), the
//    battery the top right; the fact card the upper middle (y 300-560) while it shows. Mouths move ONLY inside a
//    character's own line: ...speak(quote("di", "A03"), f, id). ji (the interviewer) is the camera: never a figure.
// =====================================================================================================================
