// HOW TO BUILD A SEGMENT (read all of it before you write code)
// =====================================================================================================================
// 0. Your files. You own shots/segX.ts and any NEW files you create with your prefix (shots/segX_*.ts). Everything
//    else is read-only for you. If you need an engine change, say so in your report.
//
// 1. The contract. shots/segX.ts exports SEG: Segment (type below):
//      export const SEG: Segment = { id: "A", from: SEGMENTS[0].from, to: SEGMENTS[0].to, enter(w) {...}, exit(w) {...}, pose(w, f) {...} };
//    from / to are inclusive absolute film frames and must equal SEGMENTS[...] (the engine checks this).
//    The engine, for every rendered frame f:
//      if the segment changed (or this is the first frame of the page):  old.exit(w); SEG.enter(w)
//      w.beginFrame(f);  const P = SEG.pose(w, f);  w.endFrame(P)
//    then draws the HUD layer, P.overlays over it, the caption of frame f over that, and P.top over everything.
//
// 2. Any frame can be the first one. The farm renders chunks that start at arbitrary frames, each in a fresh page,
//    and a still is a fresh page too. So pose(w, f) is a PURE function of f: it sets EVERY property it relies on,
//    EVERY frame. Never keep state between frames. Take time from the f you are given (t = f / FPS, or
//    (f - BEAT) / FPS), never from w.t: a shot may be re-posed at another frame (a freeze, a replay).
//    w.beginFrame(f) resets the world before every pose: no place, every figure hidden, the door flap hanging, the
//    sun disc gone, EVERY prop hidden. So what you do not set this frame is not in the picture.
//    enter(w) may fetch figures and build your own cached things once (module variables guarded by "if (!built)");
//    it runs on the first frame of every page and must not change the picture by itself.
//    Determinism: no Math.random, Date, performance.now in anything that reaches pixels. Use rng(seed) / hash(i, k).
//
// 3. Inside a shot function, in this order:
//      a. w.setPlace("tent")                       <- FIRST. It shows that place only and gives the figures that place's
//         light (the figures' solve reads the light: it cannot wait for endFrame). endFrame throws without it.
//      b. const cam = CAMS.master;  w.setCamera(cam)   <- before any figure: the figures turn to the camera and
//         every projection depends on it. Return the same cam in the Pose. Cameras come from layout.ts CAMS.
//      c. people: w.actor(PEOPLE.liuBang).set({ at, facing, pose, expr, blink, gaze, mouth, head, hands, twist, turn,
//         lookDown, hide, seat, visible: true }) for every figure in the shot. visible: true is REQUIRED.
//         Seated: ...seated(SEATS.liu, t) from shots/common.ts.
//      d. w.update(): solves all figures. After it: r.handWorld(0 | 1), r.headWorld(), r.qa.
//      e. props (props/index.ts): w.prop("shield").put(at, { yaw }) ... a prop that follows a solved hand is put now.
//         w.set.setFlap(k), w.set.setSun(u).
//      f. overlays: positions from w.project(worldPoint) -> {x, y} in 1080 x 1920 px; React nodes with h(...)
//         (segment files are .ts: no JSX).
//      g. return { camera: cam, focus?, clock?, overlays?, top?, post?, captions?, hud?, slate? }
//
// 4. The rules of this film: /home/user/hm_notes/00_director.md (the owner's rules) and 08_arthur_transitions.md.
//    Screen zones (px on 1080 x 1920, layout.ts SCREEN): nothing that matters above y 210, in the caption band
//    1190-1498, below 1613, or at x > 930 for y > 900 (the app's button rail).
//    Mouths move ONLY inside a character's own quote: ...speak(quote("xiangYu", 9), f, id).
//
// 5. Checking: see e_engine.md ("How to preview").
