// ---------------------------------------------------------------------------------------------------- the contract
export type Vec3 = [number, number, number];
export type V3Like = Vec3 | THREE.Vector3;
/** a camera pose: camera.up = up ?? (0,1,0); position = pos; lookAt(look); rotateZ(roll ?? 0); fov (vertical, degrees).
 *  A layout.ts Cam is one. */
export type CamPose = { pos: V3Like; look: V3Like; fov: number; roll?: number; up?: Vec3; near?: number; far?: number };
export type PostPose = {
  /** depth of field: focus distance (m) and blur-disc radius in px (at 1080 x 1920) of things at infinity; 0 = off */
  dof?: { focus: number; amount: number } | null;
  /** bloom intensity (threshold 1.0: only emissive / glowing things bloom); default: the place's */
  bloom?: number;
  /** default: the place's grade (sets/index.ts PlaceLook.grade), else GRADE_FILM */
  grade?: GradeParams; gradeAmount?: number;
  /** ink outline strength 0..1 (1 = default) */
  ink?: number;
  /** N8AO intensity multiplier (1 = the place's value) */
  ao?: number;
  /** scene.background instead of the place's (a CSS colour): e.g. a dimmed plate behind a silhouette */
  bg?: string;
};
export type Pose = {
  camera: CamPose;
  /** [x, z]: where the key light's shadow frustum is centred (default: under the camera's look point) */
  focus?: [number, number];
  /** seconds for the place's own animation (flames, banners): default f / FPS. The privy shots give their own clock so
   *  that the film's last frame equals its first. */
  clock?: number;
  /** 2D layer above the 3D picture and the HUD, below the captions */
  overlays?: React.ReactNode;
  /** 2D layer above the captions */
  top?: React.ReactNode;
  post?: PostPose;
  /** false hides the caption on this frame */
  captions?: boolean;
  /** false hides the HUD layer on this frame (a full-frame card, the privy shots) */
  hud?: boolean;
  /** a debug label for the animatic (drawn only with the input prop slate: true): e.g. "12b tent/dance" */
  slate?: string;
};
export type Segment = {
  id: string;
  /** inclusive absolute frames */
  from: number; to: number;
  enter(w: World): void;
  exit(w: World): void;
  /** pure function of f: pose the world and the camera, return what to show */
  pose(w: World, f: number): Pose;
};

// ---------------------------------------------------------------------------------------------------- the HUD hook
/** THE HUD LAYER: things that stay on screen across shots and segments (the 《史记》 source tag from line 3 on, ...).
 *  Film.tsx draws every registered HUD on every frame, above the 3D picture and UNDER the shot's own overlays (so a
 *  full-frame card or inset covers it), unless the shot's Pose says hud: false.
 *  The overlay builder registers at module level, once:   registerHud("source", (f, P) => f >= BEAT.source ? h(CornerTag, {...}) : null)
 *  A HUD is a pure function of the frame (and of the frame's Pose). Registering the same name again replaces it. */
export type Hud = (f: number, P: Pose) => React.ReactNode;
const HUDS: { name: string; draw: Hud }[] = [];
export const registerHud = (name: string, draw: Hud) => {
  const i = HUDS.findIndex((x) => x.name === name);
  if (i >= 0) HUDS[i] = { name, draw }; else HUDS.push({ name, draw });
};
/** the registered HUDs in the order they were registered (Film.tsx) */
export const huds = (): readonly { name: string; draw: Hud }[] => HUDS;

// ---------------------------------------------------------------------------------------------------- voice
export type VoiceLine = { n: number; text: string; from: number; to: number; start: number; end: number };
/** the narration lines in frames (from = first frame of speech, to = last); n starts at 1 */
export const LINES: VoiceLine[] = VOICE_RAW.map(([n, s, e, text]) => ({ n, text, start: s, end: e, from: Math.round(s * FPS), to: Math.round(e * FPS) }));
export const SPEECH_END = Math.round(VOICE_END_S * FPS);
/** the line with number n (1-based, as in the script). Throws when there is no such line. */
export const line = (n: number): VoiceLine => { const l = LINES[n - 1]; if (!l || l.n !== n) throw new Error(`line(${n}): the narration has ${LINES.length} lines`); return l; };
/** the line spoken at frame f (or null in a pause) */
export const lineAt = (f: number) => LINES.find((l) => f >= l.from && f <= l.to) ?? null;
/** the number of the line that frame f belongs to as PICTURE: the last line that has started 2 frames later (cuts sit 2
 *  frames before the first word) */
export const lineNo = (f: number) => { let n = 1; for (const l of LINES) if (f >= l.from - 2) n = l.n; return n; };
/** a character's own quoted words inside a narration line: who speaks (a key of PEOPLE in people.ts), the absolute
 *  frames, the seconds, the syllable count (for rigSpeak) and the text */
export type Quote = { line: number; who: Speaker; text: string; syl: number; from: number; to: number; start: number; end: number };
/** (English: the same lines' quotes with the times and syllables of the English narration, once it exists) */
export const QUOTES: Quote[] = EN && QUOTE_RAW_EN.length
  ? QUOTE_RAW_EN.map(([ln, who, s, e, syl, text]) => ({ line: ln, who, text, syl, start: s, end: e, from: Math.round(s * FPS), to: Math.round(e * FPS) }))
  : QUOTE_RAW.map(([ln, who, s, e, text]) => ({ line: ln, who, text, syl: [...text.replace(/[^一-鿿]/g, "")].length, start: s, end: e, from: Math.round(s * FPS), to: Math.round(e * FPS) }));
/** the quote of `who`; give the line when a character speaks more than once (项羽: lines 6 and 9). Throws when there is
 *  none, or when there are several and no line was given. */
export const quote = (who: Speaker, ln?: number): Quote => {
  const q = QUOTES.filter((x) => x.who === who && (ln === undefined || x.line === ln));
  if (q.length !== 1) throw new Error(`quote("${who}"${ln === undefined ? "" : `, ${ln}`}): ${q.length} quotes match${q.length > 1 ? " (give the line)" : ""}`);
  return q[0];
};

