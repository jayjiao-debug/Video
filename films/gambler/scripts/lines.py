"""Time the subtitles: each chapter window is shared by its lines in proportion to their reading need
(0.5 + chars/7 + 0.6 s), 0.1 s gaps. Prints the SUBS block for src/lib.ts."""
import re
CH = [
 ((0.10, 6.30), ['这首歌，马上要"炸"了。', '你的大脑，已经押好了注——']),
 ((6.40, 8.05), ['3、2、1——']),
 ((8.30, 10.05), ['……没炸？']),
 ((10.25, 15.40), ['你愣住的那一下，就是大脑押空了。', '再来一次。']),
 ((19.70, 32.40), ['听歌时，你的大脑一直在赌：', '下一拍是什么？和弦往哪走？', '猜对了，大脑就给你发奖励——', '哪怕猜中的，只是最普通的一拍。']),
 ((32.60, 48.60), ['可全猜中，几遍就腻；', '全猜不中，又成了噪音。', '2019年，研究者分析了8万个流行歌和弦：', '最上头的，是这两种：', '很有把握，却被骗了；', '毫无把握，却押中了。']),
 ((49.00, 60.90), ['那为什么，drop最爽？', '一项研究扫描了听歌人的大脑：', '高潮来之前，多巴胺已经开始分泌；', '高潮那一刻，再分泌一次。']),
 ((61.15, 64.45), ['注意：这首歌，真的要drop了。']),
 ((65.30, 78.70), ['从这一秒起，你的大脑就在分泌多巴胺。', '研究里，期待在高潮前十几秒就开始了。', '这就是"等"的快乐。', '那我们，让你再多等一会儿。']),
 ((79.00, 82.90), ['再等等……', '多加了一小节。']),
 ((85.00, 92.00), ['你刚才经历的，就是那个实验。', '等得越久，押中的时候越爽。']),
 ((92.10, 107.10), ['但每个人的"甜区"，不一样。', '2025年，400多人听旋律，反复二选一：', '有人偏爱好猜，有人偏爱意外——', '爱听爵士的人，甜区更靠"意外"；', '而这，和学没学过音乐无关。']),
 ((107.30, 116.40), ['所以，副歌要重复：让你押中。', 'drop前停一下：让你多押一会儿。', '你押注的依据，是听过的所有歌。']),
 ((116.70, 120.20), ['下次单曲循环，你的大脑还在赌。']),
 ((120.60, 124.20), ['你的甜区偏哪边：好猜，还是意外？']),
]
need = lambda t: 0.5 + len(re.sub(r'[，。：；、？！"“”\s—-]', '', t)) / 7 + 0.6
out, short = [], 0
for (a, z), lines in CH:
    ns = [need(t) for t in lines]; gaps = 0.1 * (len(lines) - 1)
    k = (z - a - gaps) / sum(ns)
    if k < 1: short += 1; print('!! window too short', a, z, round(k, 2))
    t = a
    for n, txt in zip(ns, lines):
        d = n * k; out.append((round(t, 2), round(t + d, 2), txt)); t += d + 0.1
print('export const SUBS: [number, number, string][] = [')
for a, z, t in out: print(f"  [{a:.2f}, {z:.2f}, '{t}'],")
print('];')
tw = sum(z - a for a, z, _ in out); tn = sum(max(0, (z - a) - need(t)) for a, z, t in out)
print(f'// waiting {100 * tn / tw:.1f}%')
