"""Time the subtitles: each chapter window is shared by its lines in proportion to their reading need
(0.5 + chars/7 + 0.6 s), 0.1 s gaps. Prints the SUBS block for src/lib.ts."""
import re
CH = [
 ((0.10, 12.05), ['100多年来，宇宙一直在朝地球"开枪"。', '有的"子弹"，能量是人类最强加速器的百万倍。', '可没人知道，枪手在哪——', '因为子弹会拐弯。']),
 ((14.30, 20.25), ['今年的诺贝尔物理学奖，', '颁给了在南极冰下找"枪手"的人。']),
 ((20.45, 32.40), ['宇宙射线带电，被磁场一路掰弯，', '落到地球，早就分不清方向。', '但现场还会飞出一个"目击者"：中微子。', '不带电，不拐弯，沿直线飞回来。']),
 ((32.62, 40.62), ['每秒100万亿个穿过你，', '一辈子撞上你的概率：1/4。', '要抓它，只能靠"大"。']),
 ((40.80, 48.70), ['1988年，哈尔岑想到：南极冰。', '深处的冰被压得没有气泡，', '清澈得惊人。']),
 ((48.95, 56.85), ['在冰下1.5到2.5公里，', '挂上5160只"眼睛"，', '2010年底完工。']),
 ((57.10, 65.00), ['中微子偶尔撞上冰里的原子，', '闪出一道蓝光；', '按光到的先后，算出来向。']),
 ((65.25, 73.60), ['每年几十亿次闪光里，', '来自宇宙深处的，只占一亿分之一。', '2013年，确认了第一批。']),
 ((73.85, 81.25), ['2017年9月22日，又一个撞进冰里，', '不到一分钟，全球望远镜一起转头——']),
 ((81.50, 89.40), ['40亿光年外，一个黑洞的喷流，', '正对着地球。', '第一次，人类指认出一个"枪手"。']),
 ((89.65, 105.65), ['2023年，它用中微子拍下了银河系：', '光被尘埃挡住的地方，它能穿过来。', '这有什么用？', '和第一台望远镜一样：', '让人类看见以前看不见的东西。']),
 ((105.95, 113.80), ['从1988年的一个想法，', '到今天的诺贝尔奖：38年。', '那些眼睛，还在冰下等。']),
 ((114.10, 121.90), ['你愿意为一个想法，等38年吗？']),
]
need = lambda t: 0.5 + len(re.sub(r'[，。：；、？！"“”\s—-]', '', t)) / 7 + 0.6
out, short = [], 0
for (a, z), lines in CH:
    ns = [need(t) for t in lines]; gaps = 0.1 * (len(lines) - 1)
    k = (z - a - gaps) / sum(ns)
    if k < 1: short += 1; print('!! window too short', a, z, round(k, 2))
    t = a
    for n, txt in zip(ns, lines):
        d = n * k; out.append((round(t, 2), round(t + d, 2), txt)); t += d + 0.1
print('export const SUBS: [number, number, string][] = [')
for a, z, t in out: print(f"  [{a:.2f}, {z:.2f}, '{t}'],")
print('];')
tw = sum(z - a for a, z, _ in out); tn = sum(max(0, (z - a) - need(t)) for a, z, t in out)
print(f'// waiting {100 * tn / tw:.1f}%')
