#!/bin/bash
# Headless clearance (clipping, 穿模) checker for any toon film with a kit.json. See README.md next to this file.
#   bash scripts/kit/qa/clearance/run.sh --film hongmen              whole film -> the film's qa.clearanceOut, {A..E}.json/.txt
#   bash scripts/kit/qa/clearance/run.sh --film hongmen --seg D      one segment (or --seg C,D)
#   bash scripts/kit/qa/clearance/run.sh --config path/kit.json ...  any film (the config may live outside the repo)
#   ... --from 1400 --to 1500 [--tol 1] [--step 1] [--out DIR] [--seed] [--quiet] [--dump F,G]
# Runs niced (the machine's cores belong to the renders); no GL, no browser, nothing is drawn.
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/../../lib/film.sh"
kit_film_args "$@" || exit 2
cd "$KIT_REPO"
CFG_DIR="$(dirname "$KIT_CONFIG")"
film=$(kit_cfg film film)
dir=$(kit_cfg dir); [ -n "$dir" ] && FILM_DIR="$KIT_REPO/$dir" || FILM_DIR="$CFG_DIR"
hooks=$(kit_cfg hooks kit.world.ts)
case "$hooks" in /*) ;; *) [ -f "$CFG_DIR/$hooks" ] && hooks="$CFG_DIR/$hooks" || hooks="$FILM_DIR/$hooks";; esac
[ -f "$hooks" ] || { echo "no hooks file $hooks (a kit.world.ts that default-exports FilmHooks: KIT.md)"; exit 2; }
out=$(kit_cfg qa.clearanceOut)
args=("${KIT_ARGS[@]}")
[ -n "$out" ] && ! printf '%s\n' "${args[@]}" | grep -qx -- "--out" && args+=(--out "$out")
B=${CLEARANCE_BUILD:-/tmp/kit_clearance_${film}_$(id -u)}
mkdir -p "$B"
# the entry: the film's hooks into the generic checker (outside the repo, like the cut's generated entries)
cat > "$B/entry.ts" <<TS
// GENERATED by scripts/kit/qa/clearance/run.sh for $film
import hooks from "${hooks%.ts}";
import { main } from "$HERE/check";
main(hooks);
TS
NODE_PATH="$KIT_REPO/node_modules${NODE_PATH:+:$NODE_PATH}" node_modules/.bin/esbuild "$B/entry.ts" --bundle --platform=node --format=cjs \
  --outfile="$B/check.js" --log-level=error --define:process.env.NODE_ENV='"production"' --banner:js="$(cat "$HERE/stub.js")"
exec nice -n 10 node --max-old-space-size=3000 "$B/check.js" "${args[@]}" 2> >(grep -v "getInputProps\|To hide this\|typeof window" >&2) | grep -v "getInputProps\|To hide this\|typeof window"
