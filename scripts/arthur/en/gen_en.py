#!/usr/bin/env python3
"""gen_en.py [en_timing.json] : writes src/videos/arthur/captions_en.ts, the English captions and the characters'
quotes (the mouths), from script_en.json.

The picture is the Chinese film's: every English group is spoken inside the window of the Chinese caption group it
stands for (captions.ts). Without a timing file the chunks of a group share that window in proportion to their
characters (a placeholder for stills). With en_timing.json (written by fit_en.py from the word times of the fitted
narration: {"lines": [{"n": 1, "end": s, "groups": [{"chunks": [[start s, end s], ...]}, ...]}]}) every chunk starts on
its first word.

Each caption carries its font size: 72 px, smaller if the chunk would be wider than 730 px, so that it stays between
x 175 and 905 like the Chinese captions: on the owner's phone the app's button column covers the picture from about
x 900 at the captions' height (measured on a Douyin screenshot), and tall phones cut about 50 px off each side."""
import json, os, re, sys
from PIL import ImageFont
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
FPS, PX, MAXW, LS = 30, 72, 730, 0.5
font = ImageFont.truetype(os.path.join(ROOT, "public/bt/sans700.ttf"), PX)
plain = lambda t: re.sub("[【】]", "", t)
words = lambda t: re.sub(r"[^a-z0-9']+", " ", plain(t).lower().replace("’", "'")).split()
SEG_OF = lambda n: "A" if n <= 5 else "B" if n <= 9 else "C" if n <= 13 else "D" if n <= 18 else "E"

script = json.load(open(os.path.join(HERE, "script_en.json"), encoding="utf8"))
zh = re.findall(r'\["([A-E])", (\d+), (\d+), "(.*?)"\],', open(os.path.join(ROOT, "src/videos/arthur/captions.ts"), encoding="utf8").read())
zh = [(s, int(a), int(b), t) for s, a, b, t in zh]
timing = json.load(open(sys.argv[1], encoding="utf8")) if len(sys.argv) > 1 else None

caps, quotes, gi = [], [], 0
for li, ln in enumerate(script["lines"]):
    n = ln["n"]; qs = {}; rows = []
    G = ln.get("alt", {}).get(timing["lines"][li].get("take"), ln["groups"]) if timing else ln["groups"]
    for k, g in enumerate(G):
        seg, a, b, zt = zh[gi]; gi += 1
        assert seg == SEG_OF(n), (n, seg)
        assert words(" ".join(g["cap"])) == words(g["t"]), (n, g["cap"], g["t"])
        if timing:
            ch = timing["lines"][li]["groups"][k]["chunks"]; assert len(ch) == len(g["cap"]), (n, k)
            spans = [(s, e) for s, e in ch]
        else:   # placeholder: share the Chinese group's window by characters
            tot = sum(len(plain(c)) for c in g["cap"]); acc = 0; spans = []
            for c in g["cap"]:
                s0 = a + (b + 1 - a) * acc / tot; acc += len(plain(c)); spans.append((s0 / FPS, (a + (b + 1 - a) * acc / tot) / FPS))
        for c, (s0, e0) in zip(g["cap"], spans): rows.append([round(s0 * FPS), round(e0 * FPS), c])
        if g.get("who"):
            q = qs.setdefault(g["who"], {"s": spans[0][0], "e": spans[-1][1], "syl": 0, "t": ""})
            q["e"] = spans[-1][1]; q["syl"] += g["syl"]; q["t"] = (q["t"] + " " + g["t"]).strip()
    # a chunk stays up until the next one starts; the last one of a line until the line's last frame
    end_f = round(timing["lines"][li]["end"] * FPS) if timing else zh[gi - 1][2]
    for i, r in enumerate(rows):
        to = rows[i + 1][0] - 1 if i + 1 < len(rows) else max(end_f, r[0] + 6)
        t = plain(r[2]); w = font.getlength(t) + LS * len(t); px = PX if w <= MAXW else int(PX * MAXW / w)
        caps.append([SEG_OF(n), r[0], max(r[0], to), r[2], px, round(w * px / PX)])
    for who, q in qs.items(): quotes.append([n, who, round(q["s"], 3), round(q["e"], 3), q["syl"], q["t"].replace('"', "")])
assert gi == len(zh), (gi, len(zh))
for i in range(1, len(caps)):   # captions of consecutive lines must not overlap
    if caps[i][1] <= caps[i - 1][2]: caps[i - 1][2] = caps[i][1] - 1
    assert caps[i - 1][2] >= caps[i - 1][1], caps[i - 1]
with open(os.path.join(ROOT, "src/videos/arthur/captions_en.ts"), "w", encoding="utf8") as f:
    f.write("// GENERATED by scripts/arthur/en/gen_en.py from script_en.json" + (" and the fitted English narration" if timing else " (PLACEHOLDER timing: the Chinese windows)") + ": do not edit by hand.\n")
    f.write("// The English captions: [segment, first frame, last frame (inclusive), text, font px, width px]. 【】 marks the gold key\n// words. Drawn by <Caption> in Film.tsx when lang is \"en\".\n")
    f.write('import type { CaptionGroup } from "./captions";\n\nexport type CaptionEN = CaptionGroup & { px: number; w: number };\n')
    f.write("const RAW: [string, number, number, string, number, number][] = [\n")
    for c in caps: f.write("  " + json.dumps(c, ensure_ascii=False) + ",\n")
    f.write("];\n")
    f.write('''export const CAPTIONS_EN: CaptionEN[] = RAW.map(([shot, from, to, text, px, w]) => ({ shot, from, to, text, px, w }));
export const captionAtEN = (f: number): CaptionEN | null => {
  let lo = 0, hi = CAPTIONS_EN.length - 1;
  while (lo <= hi) {
    const m = (lo + hi) >> 1, c = CAPTIONS_EN[m];
    if (f < c.from) hi = m - 1; else if (f > c.to) lo = m + 1; else return c;
  }
  return null;
};
for (let i = 1; i < CAPTIONS_EN.length; i++) {
  if (CAPTIONS_EN[i].from <= CAPTIONS_EN[i - 1].to) throw new Error(`English caption groups overlap at ${CAPTIONS_EN[i].text}`);
}
/** a character's own words inside a line: [line, who, start s, end s, syllables, the words] */
export const QUOTE_RAW_EN: [number, "kay" | "arthur" | "lord" | "commons", number, number, number, string][] = [
''')
    for q in quotes: f.write("  " + json.dumps(q, ensure_ascii=False) + ",\n")
    f.write("];\n")
print("captions", len(caps), "| narrowed:", [(c[3], c[4]) for c in caps if c[4] < PX], "| quotes", quotes)
