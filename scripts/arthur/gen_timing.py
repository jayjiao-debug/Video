#!/usr/bin/env python3
"""Writes src/videos/arthur/voice.ts and captions.ts from the narration's line timing.
usage: gen_timing.py <voice_timing.json | --placeholder>
voice_timing.json: {"lines": [{"line": 1, "text": "...", "start": s, "end": s}, ...], "speech_end": s}
Caption groups and the characters' quoted words are placed inside a line in proportion to the Chinese characters
before them (pauses inside a line are compressed in the edit, so the speech rate inside a line is nearly even)."""
import json, re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FPS = 30
# one entry per narration line: the caption groups (【】 = gold key words); a group that is a character's own words is
# (text, who). The groups of a line, joined and stripped of marks, must equal the line's text without punctuation.
CAP = [
 ["他把刚拔出来的【石中剑】", "又【插了回去】"],
 ["等等", "拔出来不就是【国王】吗？"],
 ["名著【《亚瑟王之死》】里", "伦敦教堂院子里", "多了块【大石头】", "插着把剑"],
 ["【金字】写着", "谁拔出来", "谁就是【国王】"],
 ["【贵族】排队来拔", "脸都憋红了", "剑【一动不动】"],
 ["新年【比武大会】", "亚瑟的哥哥叫【凯】", "刚当上骑士", "一摸腰", "【剑忘带了】"],
 ["【亚瑟】回去拿", "家里【没人】", "全看比武去了"],
 ["他想起", "石头上【还插着一把】"],
 ["连【十个守卫】", "都看比武去了", "他一拔就出来", "【第一次】"],
 ["凯拿到剑就找爸爸", ("“爸，【石中剑】！”", "kay"), ("“我要当【国王】了！”", "kay")],
 ["爸爸让他【发誓】", "凯才承认", "是【弟弟】拿的"],
 ["爸爸让亚瑟【插回去】", "【再拔一次】", "他说", ("“这有什么难的。”", "arthur")],
 ["爸爸先拔", "【不动】", "凯使出吃奶的劲", "【不动】", "亚瑟一伸手", "【第二次】"],
 ["几天后贵族全来试", "只有他拔得出", "【第三次】"],
 ["他们【气炸了】", ("“让个出身不高的小子”", "lord"), ("“管我们？”", "lord"), "说【改天再拔】"],
 ["二月", "雪还没化", "【第四次】", "又拖"],
 ["春天", "花都开了", "【第五次】", "还拖"],
 ["初夏", "当着所有人的面", "【第六次】"],
 ["【老百姓】急了", ("“就要亚瑟当国王”", "commons"), ("“【别再拖了】！”", "commons")],
 ["所有人齐刷刷【跪下】"],
 ["整整【六次】", "他才当上国王", "而第一次", "只因为哥哥【忘了带剑】"],
]
SEG_OF = lambda n: "A" if n <= 5 else "B" if n <= 9 else "C" if n <= 13 else "D" if n <= 18 else "E"
cjk = lambda s: len(re.findall(r"[一-鿿]", s))
strip = lambda s: re.sub(r"[^一-鿿]", "", s)

def main():
    arg = sys.argv[1]
    if arg == "--placeholder":
        lines = json.load(open(sys.argv[2], encoding="utf8"))
        t, rows = 0.0, []
        for i, tx in enumerate(lines, 1):
            d = cjk(tx) / 5.6
            rows.append({"line": i, "text": tx, "start": round(t, 3), "end": round(t + d, 3)}); t += d + 0.06
        end = rows[-1]["end"]
    else:
        j = json.load(open(arg, encoding="utf8")); rows = j["lines"]; end = j.get("speech_end", rows[-1]["end"])
    assert len(rows) == len(CAP), (len(rows), len(CAP))
    caps, quotes = [], []
    for r, groups in zip(rows, CAP):
        n, s, e = r["line"], r["start"], r["end"]
        texts = [g if isinstance(g, str) else g[0] for g in groups]
        assert strip("".join(texts)) == strip(r["text"]), (n, "".join(texts), r["text"])
        tot = cjk(r["text"]); acc = 0; qs = {}
        f0, f1 = round(s * FPS), round(e * FPS)
        for gi, g in enumerate(groups):
            tx = texts[gi]; k = cjk(tx)
            a = s + (e - s) * acc / tot; b = s + (e - s) * (acc + k) / tot; acc += k
            ga = f0 if gi == 0 else round(a * FPS); gb = (f1 if gi == len(groups) - 1 else round(b * FPS) - 1)
            caps.append((SEG_OF(n), ga, max(ga, gb), tx))
            if not isinstance(g, str):
                who = g[1]; q = qs.setdefault(who, {"s": a, "e": b, "t": ""}); q["e"] = b; q["t"] += strip(tx)
        for who, q in qs.items(): quotes.append((n, who, round(q["s"], 3), round(q["e"], 3), q["t"]))
    # captions of consecutive lines must not overlap
    for i in range(1, len(caps)):
        if caps[i][1] <= caps[i - 1][2]: caps[i - 1] = (caps[i - 1][0], caps[i - 1][1], caps[i][1] - 1, caps[i - 1][3])
    d = os.path.join(ROOT, "src/videos/arthur")
    with open(os.path.join(d, "voice.ts"), "w", encoding="utf8") as f:
        f.write("// GENERATED by scripts/arthur/gen_timing.py from the recorded narration: do not edit by hand.\n")
        f.write("/** [line number, start s, end s, text] */\nexport const VOICE_RAW: [number, number, number, string][] = [\n")
        for r in rows: f.write(f"  [{r['line']}, {r['start']}, {r['end']}, {json.dumps(r['text'], ensure_ascii=False)}],\n")
        f.write("];\n")
        f.write(f"export const VOICE_END_S = {end};\n")
        f.write("/** a character's own words inside a line: [line, who, start s, end s, the words] */\n")
        f.write('export const QUOTE_RAW: [number, "kay" | "arthur" | "lord" | "commons", number, number, string][] = [\n')
        for q in quotes: f.write(f"  [{q[0]}, {json.dumps(q[1])}, {q[2]}, {q[3]}, {json.dumps(q[4], ensure_ascii=False)}],\n")
        f.write("];\n")
    with open(os.path.join(d, "captions.ts"), "w", encoding="utf8") as f:
        f.write("// GENERATED by scripts/arthur/gen_timing.py from the recorded narration: do not edit by hand.\n")
        f.write("// Caption groups: [segment, first frame, last frame (inclusive), text]. 【】 marks the gold key words (the brackets\n// are not drawn). Drawn by <Caption> in Film.tsx.\n")
        f.write("export type CaptionGroup = { from: number; to: number; text: string; shot: string };\nexport type CaptionRun = { text: string; gold: boolean };\n\n")
        f.write("const RAW: [string, number, number, string][] = [\n")
        for c in caps: f.write(f"  [{json.dumps(c[0])}, {c[1]}, {c[2]}, {json.dumps(c[3], ensure_ascii=False)}],\n")
        f.write("];\n")
        f.write('''export const CAPTIONS: CaptionGroup[] = RAW.map(([shot, from, to, text]) => ({ shot, from, to, text }));
export const captionAt = (f: number): CaptionGroup | null => {
  let lo = 0, hi = CAPTIONS.length - 1;
  while (lo <= hi) {
    const m = (lo + hi) >> 1, c = CAPTIONS[m];
    if (f < c.from) hi = m - 1; else if (f > c.to) lo = m + 1; else return c;
  }
  return null;
};
/** "我的朋友【不会】" -> [{text: "我的朋友", gold: false}, {text: "不会", gold: true}] */
export const captionRuns = (text: string): CaptionRun[] => {
  const out: CaptionRun[] = [];
  const re = /【([^】]*)】/g;
  let i = 0, m: RegExpExecArray | null;
  while ((m = re.exec(text))) {
    if (m.index > i) out.push({ text: text.slice(i, m.index), gold: false });
    out.push({ text: m[1], gold: true });
    i = m.index + m[0].length;
  }
  if (i < text.length) out.push({ text: text.slice(i), gold: false });
  return out;
};
/** trailing punctuation that is pulled back by half an em so the line stays optically centred */
export const TRAILING_PUNCT = "？！，。：”";
for (let i = 1; i < CAPTIONS.length; i++) {
  if (CAPTIONS[i].from <= CAPTIONS[i - 1].to) throw new Error(`caption groups overlap at ${CAPTIONS[i].text}`);
}
''')
    print("lines", len(rows), "captions", len(caps), "quotes", quotes, "end", end, "frames", round(end * FPS) + 12)

main()
