// HUMPHREY'S TRACK for skin A's banner (EFFECTS_PLAN row 2): poses the real World headlessly (as scripts/newton/qa/faces
// does, with the clearance tool's stub) over the banner's frames (hud/ms/when.ts msItem("banner"), fit_A.ts included)
// and writes src/videos/newton/hud/ms/track.ts: Humphrey's head on screen per frame (hud/ms/screen.ts msFig: centre x,
// y and radius, film px). The faces checker and check.ts read the banner's per-frame boxes from it. RUN IT AFTER ANY
// CHANGE TO segA OR TO THE BANNER'S FRAMES (fit_A.ts), then check.sh and the faces checker:
//   bash scripts/newton/ms/track.sh             (writes track.ts; prints the frames probed)
//   bash scripts/newton/ms/track.sh --dry       (prints the track, writes nothing)
// From the r2 probe (/home/user/newton_work/film/skinA/r2/probe: probe_hum.ts + make_track.py), as one tool.
import * as THREE from "three";
import * as fs from "fs";
import hooks from "../../../src/videos/newton/kit.world";
import { msScreen, msFig } from "../../../src/videos/newton/hud/ms/screen";
import { msItem } from "../../../src/videos/newton/hud/ms/when";
import { W, H } from "../../../src/videos/newton/story";
declare const process: { argv: string[]; exit(c: number): never };
const DRY = process.argv.includes("--dry");
/** the generated file (track.sh runs from the repo root) */
const OUT = "src/videos/newton/hud/ms/track.ts";
const it = msItem("banner");
const camera = new THREE.PerspectiveCamera(40, W / H, 0.03, 600);
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const w: any = hooks.makeWorld((globalThis as any).__mk(), camera);
// eslint-disable-next-line @typescript-eslint/no-explicit-any
let cur: any = null;
const rows: { f: number; x: number; y: number; r: number }[] = [];
for (let f = it.from; f <= it.to; f++) {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const s = hooks.segments.find((g: any) => f >= g.from && f <= g.to)!;
  if (s !== cur) { cur?.exit?.(w); s.enter?.(w); cur = s; }
  w.beginFrame(f); const P = s.pose(w, f); w.endFrame(P); w.root.updateMatrixWorld(true); camera.updateMatrixWorld();
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const g = msFig(msScreen(w, P as any, f, f), "humphrey");
  if (!g) { console.error(`track: Humphrey is not on screen on f${f} (the banner's frames are ${it.from}-${it.to}): fix segA or the banner's frames in fit_A.ts`); process.exit(1); }
  rows.push({ f, x: Math.round(g.head.x), y: Math.round(g.head.y), r: Math.round(g.r) });
}
const nums = rows.map((r) => `${r.x},${r.y},${r.r}`).join(",");
const out = `// hud/ms/track.ts: GENERATED by scripts/newton/ms/track.sh (never edit by hand; the A builder re-runs it).
// HUMPHREY'S HEAD ON SCREEN over his banner (EFFECTS_PLAN row 2), per frame of segA: centre x, y and radius (film px),
// as hud/ms/screen.ts msFig gives them, from the banner's first frame (t 0 = film frame ${it.from}) for ${rows.length} frames (its
// last: ${it.to}). Why: the faces checker and check.ts read an item's boxes from the frame number alone (hud/index.ts
// hudRectsAt), while the banner rides his head on every frame; this track gives them the same per-frame boxes the banner
// draws in (when.ts banner boxAt, bannerplace.ts). The banner draws from the live head and is held within a few px of
// this track, so a stale track shows in the stills and the checkers. RE-PROBE after any change to segA or the banner.
export const HUMPHREY_TRACK: { first: number; n: number; xyr: readonly number[] } = {
  first: ${it.from}, n: ${rows.length},
  xyr: [${nums}],
};
`;
if (DRY) console.log(out);
else { fs.writeFileSync(OUT, out); console.log(`track: wrote ${OUT}: ${rows.length} frames from f${it.from}`); }
